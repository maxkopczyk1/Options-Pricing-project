# ============================================================
# EXPERIMENT 10: HISTORICAL-UNDERLYING DEMO BACKTEST
# ============================================================
#
# PURPOSE
# -------
# Test the FROZEN robust event-driven hedge thresholds from
# Experiment 9 on real historical stock-price paths.
#
# Important:
# This is NOT a backtest of actual historical listed option prices.
# We create demo European call options on real historical underlying
# paths and use trailing realised volatility as an ex-ante volatility
# proxy when pricing/hedging them.
#
# Therefore the main comparison is:
#
#       DAILY HEDGING
#               vs
#       FROZEN EVENT-DRIVEN HEDGING
#
# We focus on:
#   - P&L dispersion across historical option windows
#   - transaction costs
#   - hedge turnover / rebalance count
#
# The event-driven thresholds are NOT re-optimised here.


# ============================================================
# SETTINGS
# ============================================================

RISK_FREE_RATE = 0.05
TRANSACTION_COST_RATE = 0.001      # 0.10% = 10 bps

# Use the robust thresholds generated by Experiment 9.
ROBUST_RESULTS_FILE = Path(
    "experiment_09_robust_validation.csv"
)

# 60 prior trading days are used to estimate annualised volatility.
VOL_LOOKBACK_DAYS = 60

# Quarterly historical start dates.
# This gives multiple real market paths without tuning on them.
START_DATES = pd.date_range(
    start="2018-01-02",
    end="2024-01-02",
    freq="QS",
)

# Download enough history for the lookback and the final 1Y option.
DOWNLOAD_START = "2017-08-01"
DOWNLOAD_END = "2025-03-01"


