# DOWNLOAD HISTORICAL UNDERLYING PRICES
# ============================================================

def download_close_prices(ticker):
    data = yf.download(
        ticker,
        start=DOWNLOAD_START,
        end=DOWNLOAD_END,
        auto_adjust=True,
        progress=False,
    )

    if data.empty:
        raise ValueError(
            f"No historical data returned for {ticker}."
        )

    close = data["Close"]

    # Recent yfinance versions may return a one-column DataFrame.
    if isinstance(close, pd.DataFrame):
        close = close.iloc[:, 0]

    close = close.dropna().astype(float)

    return close


