# ============================================================
# HELPERS
# ============================================================

def annualised_volatility(price_series):
    log_returns = np.diff(
        np.log(
            np.asarray(
                price_series,
                dtype=float,
            )
        )
    )

    if len(log_returns) < 2:
        raise ValueError(
            "Not enough observations to estimate volatility."
        )

    return float(
        np.std(
            log_returns,
            ddof=1,
        )
        * np.sqrt(252)
    )


def build_historical_option_window(
    prices,
    requested_start,
    horizon_steps,
):
    """
    Return:
        stock_path,
        actual_start_date,
        pricing_sigma

    pricing_sigma uses ONLY information available before the
    option start date.
    """
    index = prices.index

    position = index.searchsorted(
        pd.Timestamp(requested_start)
    )

    # Need enough prior observations for the volatility estimate.
    if position < VOL_LOOKBACK_DAYS + 1:
        return None

    # Need horizon_steps + 1 prices including the initial price.
    final_position = position + horizon_steps

    if final_position >= len(prices):
        return None

    lookback = prices.iloc[
        position - VOL_LOOKBACK_DAYS - 1:
        position
    ]

    stock_path = prices.iloc[
        position:
        final_position + 1
    ].to_numpy(dtype=float)

    pricing_sigma = annualised_volatility(
        lookback
    )

    actual_start_date = index[position]

    return (
        stock_path,
        actual_start_date,
        pricing_sigma,
    )


