def load_robust_thresholds(csv_path):
    if not csv_path.exists():
        raise FileNotFoundError(
            f"Could not find {csv_path}.\n"
            "Run experiment_09_robust_optimisation.py first."
        )

    thresholds = {}

    with open(
        csv_path,
        "r",
        encoding="utf-8",
        newline="",
    ) as file:
        reader = csv.DictReader(file)

        for row in reader:
            scenario = row["Scenario"]
            threshold = float(
                row["Selected Threshold"]
            )

            if scenario in thresholds:
                if not np.isclose(
                    thresholds[scenario],
                    threshold,
                ):
                    raise ValueError(
                        f"Multiple different thresholds "
                        f"found for {scenario}."
                    )
            else:
                thresholds[scenario] = threshold

    return thresholds


ROBUST_THRESHOLDS = load_robust_thresholds(
    ROBUST_RESULTS_FILE
)

