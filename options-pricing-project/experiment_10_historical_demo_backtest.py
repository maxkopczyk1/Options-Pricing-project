detailed_rows = []


for demo_name, params in DEMO_SCENARIOS.items():

    ticker = params["ticker"]

    robust_scenario = (
        params["robust_scenario_name"]
    )

    if robust_scenario not in ROBUST_THRESHOLDS:
        raise KeyError(
            f"No frozen robust threshold found for "
            f"{robust_scenario}."
        )

    threshold = ROBUST_THRESHOLDS[
        robust_scenario
    ]

    prices = price_data[ticker]

    print("\n" + "=" * 80)
    print(f"HISTORICAL DEMO: {demo_name}")
    print("=" * 80)

    print(
        f"Frozen threshold: "
        f"{threshold:.3f}"
    )

    successful_windows = 0

    for requested_start in START_DATES:

        built = build_historical_option_window(
            prices=prices,
            requested_start=requested_start,
            horizon_steps=params[
                "horizon_steps"
            ],
        )

        if built is None:
            continue

        (
            stock_path,
            actual_start_date,
            pricing_sigma,
        ) = built

        S0 = float(stock_path[0])

        K = (
            S0
            * params["strike_multiplier"]
        )

        T = (
            params["horizon_steps"]
            / 252
        )

        # ----------------------------------------------------
        # DAILY FIXED HEDGE
        # ----------------------------------------------------

        daily = hedge_single_path(
            stock_path=stock_path,
            K=K,
            T=T,
            r=RISK_FREE_RATE,
            pricing_sigma=pricing_sigma,
            transaction_cost_rate=(
                TRANSACTION_COST_RATE
            ),
        )

        # ----------------------------------------------------
        # FROZEN EVENT-DRIVEN HEDGE
        # ----------------------------------------------------

        event = (
            hedge_single_path_event_driven(
                stock_path=stock_path,
                K=K,
                T=T,
                r=RISK_FREE_RATE,
                pricing_sigma=pricing_sigma,
                delta_threshold=threshold,
                transaction_cost_rate=(
                    TRANSACTION_COST_RATE
                ),
            )
        )

        daily_rebalances = (
            len(stock_path) - 2
        )

        cost_saving = (
            (
                daily[
                    "total_transaction_cost"
                ]
                - event[
                    "total_transaction_cost"
                ]
            )
            / daily[
                "total_transaction_cost"
            ]
            * 100
        )

        rebalance_reduction = (
            (
                daily_rebalances
                - event["rebalance_count"]
            )
            / daily_rebalances
            * 100
            if daily_rebalances > 0
            else 0.0
        )

        detailed_rows.append({
            "Demo Scenario": demo_name,
            "Robust Scenario": robust_scenario,
            "Ticker": ticker,
            "Start Date": (
                actual_start_date.date()
            ),
            "Start Price": S0,
            "Strike": K,
            "Time to Expiry": T,
            "Pricing Volatility": pricing_sigma,
            "Frozen Threshold": threshold,
            "Final Stock Price": (
                float(stock_path[-1])
            ),
            "Daily P&L": daily["pnl"],
            "Event P&L": event["pnl"],
            "Daily Transaction Cost": (
                daily[
                    "total_transaction_cost"
                ]
            ),
            "Event Transaction Cost": (
                event[
                    "total_transaction_cost"
                ]
            ),
            "Transaction Cost Saving %": (
                cost_saving
            ),
            "Daily Rebalances": (
                daily_rebalances
            ),
            "Event Rebalances": (
                event["rebalance_count"]
            ),
            "Rebalance Reduction %": (
                rebalance_reduction
            ),
        })

        successful_windows += 1

    print(
        f"Historical option windows tested: "
        f"{successful_windows}"
    )


# ============================================================
# SUMMARISE HISTORICAL PERFORMANCE
# ============================================================

summary_rows = []


for demo_name in DEMO_SCENARIOS:

    rows = [
        row
        for row in detailed_rows
        if row["Demo Scenario"] == demo_name
    ]

    if len(rows) < 2:
        continue

    daily_pnls = np.array([
        row["Daily P&L"]
        for row in rows
    ])

    event_pnls = np.array([
        row["Event P&L"]
        for row in rows
    ])

    daily_costs = np.array([
        row["Daily Transaction Cost"]
        for row in rows
    ])

    event_costs = np.array([
        row["Event Transaction Cost"]
        for row in rows
    ])

    daily_rebalances = np.array([
        row["Daily Rebalances"]
        for row in rows
    ])

    event_rebalances = np.array([
        row["Event Rebalances"]
        for row in rows
    ])

    daily_sd = float(
        np.std(
            daily_pnls,
            ddof=1,
        )
    )

    event_sd = float(
        np.std(
            event_pnls,
            ddof=1,
        )
    )

    risk_change = (
        event_sd / daily_sd - 1
    ) * 100

    cost_saving = (
        (
            np.mean(daily_costs)
            - np.mean(event_costs)
        )
        / np.mean(daily_costs)
        * 100
    )

    rebalance_reduction = (
        (
            np.mean(daily_rebalances)
            - np.mean(event_rebalances)
        )
        / np.mean(daily_rebalances)
        * 100
    )

    robust_scenario = rows[0][
        "Robust Scenario"
    ]

    frozen_threshold = rows[0][
        "Frozen Threshold"
    ]

    summary = {
        "Demo Scenario": demo_name,
        "Robust Scenario": robust_scenario,
        "Frozen Threshold": frozen_threshold,
        "Historical Windows": len(rows),
        "Daily P&L Mean": float(
            np.mean(daily_pnls)
        ),
        "Event P&L Mean": float(
            np.mean(event_pnls)
        ),
        "Daily P&L SD": daily_sd,
        "Event P&L SD": event_sd,
        "Risk Change %": risk_change,
        "Daily Mean Cost": float(
            np.mean(daily_costs)
        ),
        "Event Mean Cost": float(
            np.mean(event_costs)
        ),
        "Cost Saving %": cost_saving,
        "Daily Mean Rebalances": float(
            np.mean(daily_rebalances)
        ),
        "Event Mean Rebalances": float(
            np.mean(event_rebalances)
        ),
        "Rebalance Reduction %": (
            rebalance_reduction
        ),
    }

    summary_rows.append(summary)


